/**
 * 语音输出格式提示（systemPrompt 段落）。
 *
 * 为什么要这一段：
 *   小米 MiMo TTS 支持用括号标签控制语气——开头写 `(慵懒)`、句中插 `[叹气]`。
 *   但模型默认不知道这个规矩，只会输出带括号动作描写的「舞台剧」格式（**（歪头）那个……**），
 *   那些括号会被 TTS 逐字念出来，听起来就很怪。
 *
 *   所以切到小米时，额外告诉模型：正文就是「要播出去的台词」，
 *   语气请用 `(风格)` 和 `[标签]`，不要写动作描写。
 *   切回 DeepSeek 时这一段自动消失（text 返回空串），模型恢复原来的输出习惯。
 */

/** 段落在提示词里的排序位（放在工具引导之后、人设后缀之前）。 */
const SECTION_ORDER = 3000

/** 段落名（改动会触发 prompt 重算）。 */
const SECTION_NAME = 'companion-voice:speech-format'

/** 小米输出规格（只在 engine=mimo 时注入）。 */
export function mimoSpeechGuidance(style: string): string {
  const styleLine = style.trim() || '语气温柔，自然语速'
  return [
    '## 语音播报格式（当前通道：小米 MiMo TTS）',
    '',
    '你的回复会被直接转成语音播放，所以请按下面的规矩写：',
    '',
    '1. **只写要念出来的话**。不要写动作描写、心理描写、舞台指示——',
    '   例如「（歪头）」「（凑近，声音软软的）」「*轻轻晃腿*」这类内容都会被逐字念出来，很难听。',
    '2. **用标签控制语气**，不要用括号描述动作：',
    '   - 开头放一个整体风格标签，例如 `(慵懒)` `(俏皮)` `(温柔)` `(低沉)`；',
    '   - 句中需要转折时插方括号标签，例如 `[叹气]` `[轻笑]` `[语速加快]` `[气声]` `[停顿]`。',
    '3. **标签只是表演指令，不会被念出来**；但括号里的动作描写会被念出来。',
    `4. 本次设定的声音：${styleLine}`,
    '',
    '示例（推荐写法）：',
    '```',
    '(温柔)你回来啦？[轻笑]我等你好久了。[停顿]今天累不累？',
    '```',
    '',
    '示例（不要这样写）：',
    '```',
    '（歪头，头发从肩上滑下来）那个……你先听我说……',
    '```',
  ].join('\n')
}

/** DeepSeek 通道的规格（保持简洁，不干扰原有风格）。 */
export function deepseekSpeechGuidance(): string {
  return ''
}
